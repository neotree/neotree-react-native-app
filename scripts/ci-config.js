// Creates a placeholder src/config.ts for CI from the committed config/config-example.json.
//
// src/config.ts holds real endpoints and API keys, so it is git-ignored and CI never has
// it. Without it, lint and typecheck fail on `import configJSON from '../config'` in
// src/constants. Run only by `ci:prepare` (never by postinstall or EAS), and it never
// replaces an existing file, so a developer's or a build's real config is left alone.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const target = path.join(root, 'src', 'config.ts');
const example = path.join(root, 'config', 'config-example.json');

if (fs.existsSync(target)) {
    console.log('ci-config: src/config.ts exists; leaving it untouched.');
} else {
    const placeholder = JSON.parse(fs.readFileSync(example, 'utf8'));
    fs.writeFileSync(
        target,
        '// Generated by scripts/ci-config.js from config/config-example.json for CI checks only.\n' +
        `export default ${JSON.stringify(placeholder, null, 4)};\n`,
    );
    console.log('ci-config: wrote placeholder src/config.ts from config/config-example.json.');
}
